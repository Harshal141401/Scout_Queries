--  ord 0 prints this version and "10 objects / 28 columns needed"; every
--  object row says "N needed".
--
--  OUTPUT  ord | object_name | needed_count | needed_columns | type_flags |
--          visible_as | columns_present
--  Every object row (ord 1-10) must say ALL OK. Metadata only (ALL_OBJECTS,
--  ALL_SYNONYMS, ALL_TAB_COLUMNS). No binds. Pure SELECT. Nothing is written.
