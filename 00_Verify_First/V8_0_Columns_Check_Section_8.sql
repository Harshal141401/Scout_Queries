--              FND_APPLICATION_VL (proven by R003); drops LAST_ACCESSED_DATE
--              (R033: it equals LAST_MODIFIED_DATE). NO RE-RUN NEEDED on this
--              pod: every column below was printed by R031 or R003.
--              v1.0 ran as R031 (9 / 9 ALL OK).
--  NOT CHECKED HERE: ESS_REQUEST_HISTORY (DEFINITION, JOBTYPE, NAME,
--  PROCESSSTART, PRODUCT, SUBMITTER). The data dictionary shows no column for
